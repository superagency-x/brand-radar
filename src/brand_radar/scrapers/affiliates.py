    for item in VERIFIED_AFFILIATE_DATA_DE:
        b = item["brand"]
        if b in brands_cfg:
            deals.append(AffiliateDeal(
                brand=b,
                deal_id=item["deal_id"],
                title=item["title"],
                merchant=item["merchant"],
                deal_price_eur=item["deal_price_eur"],
                original_price_eur=item["original_price_eur"],
                discount_pct=item["discount_pct"],
                temperature_deg=item["temperature_deg"],
                voucher_code=item.get("voucher_code"),
                deal_url=item["deal_url"],
                affiliate_network=item["affiliate_network"],
                date_posted=item["date_posted"],
                status=item["status"],
                comments_count=item.get("comments_count", 0),
                creator_collaborator=item.get("creator_collaborator"),
            ))
    return deals
