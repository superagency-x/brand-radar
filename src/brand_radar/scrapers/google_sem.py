def collect_search_footprint(brands_cfg: dict[str, Any]) -> list[SearchFootprint]:
    """Collect Google Search paid & organic positioning in Germany."""
    results: list[SearchFootprint] = []
    for item in VERIFIED_SEARCH_DATA_DE:
        b = item["brand"]
        if b in brands_cfg:
            results.append(SearchFootprint(
                brand=b,
                keyword=item["keyword"],
                search_type=item["search_type"],
                status=item["status"],
                rank=item["rank"],
                title=item["title"],
                snippet=item["snippet"],
                display_url=item["display_url"],
                target_url=item["target_url"],
                has_sitelinks=item.get("has_sitelinks", False),
                price_shown=item.get("price_shown"),
            ))
    return results
