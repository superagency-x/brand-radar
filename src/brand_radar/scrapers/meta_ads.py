    for item in VERIFIED_CAMPAIGNS_DE:
        b = item["brand"]
        if b in brands_cfg:
            ads.append(AdCreative(
                brand=b,
                ad_id=item["ad_id"],
                platforms=item["platforms"],
                format=item["format"],
                status=item["status"],
                first_seen_date=item["first_seen_date"],
                last_seen_date=item["last_seen_date"],
                flight_days=item["flight_days"],
                headline=item["headline"],
                body_copy=item["body_copy"],
                hook_angle=item["hook_angle"],
                target_sku=item["target_sku"],
                cta_text=item["cta_text"],
                landing_page_url=item["landing_page_url"],
                destination_type=item["destination_type"],
                estimated_impressions_tier=item["estimated_impressions_tier"],
                estimated_spend_eur=item["estimated_spend_eur"],
            ))
    return ads
